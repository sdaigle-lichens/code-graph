#!/usr/bin/env node
// Regenerates the plugin's bundled CLI, plugin/scripts/code-graph.cjs, from src/cli.ts.
//
//   pnpm bundle            (root; turbo task `bundle`, also run by the root `pnpm build`)
//
// The plugin ships by file copy and its skills run `node "${CLAUDE_PLUGIN_ROOT}/scripts/code-graph.cjs"`
// with no node_modules beside it, so the bundle is self-contained and COMMITTED.
//
// Two dependencies are deliberately NOT bundled: `typescript` and `ts-morph` (tens of megabytes).
// Every import of either is rewritten to `requireFromProject` (src/project-deps.ts), which loads
// the copy in the plugin-owned deps directory (`code-graph deps install`) first, then the project's
// own via `createRequire(<project>/package.json)`, and fails naming `deps install` when neither has it. `node:sqlite` is a builtin and stays a plain
// lazy require. The `skills` layer reaches none of the three.
//
// IT FAILS QUIETLY: if this stops producing correct output the committed .cjs keeps working while
// edits to src/ stop reaching the plugin. After changing anything here, re-run it and read
// `git diff plugin/scripts/`.

import { build } from "esbuild";
import { readFileSync, statSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { assertVersionsAligned } from "./check-versions.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));
const pkgRoot = path.resolve(here, "..");
const defaultOutfile = path.resolve(pkgRoot, "../../plugin/scripts/code-graph.cjs");
const pkg = JSON.parse(readFileSync(path.join(pkgRoot, "package.json"), "utf8"));

const BANNER = `// GENERATED by packages/code-graph/scripts/build-plugin.mjs — DO NOT EDIT.
// Source: packages/code-graph/src/cli.ts
// Regenerate with: pnpm bundle (or pnpm build) from the repository root.`;

const PROJECT_DEPS = /^(typescript|ts-morph)$/;

/** Route `typescript` / `ts-morph` through the project-relative loader instead of bundling them. */
const projectDeps = {
  name: "project-deps",
  setup(b) {
    b.onResolve({ filter: PROJECT_DEPS }, (args) => ({ path: args.path, namespace: "project-dep" }));
    b.onLoad({ filter: /.*/, namespace: "project-dep" }, (args) => ({
      contents:
        `const { requireFromProject } = require("./project-deps.ts");\n` +
        `module.exports = requireFromProject(${JSON.stringify(args.path)});\n`,
      resolveDir: path.join(pkgRoot, "src"),
      loader: "js",
    }));
  },
};

/** Build the bundle into `outfile` (default: the committed plugin script). Exported for tests. */
export async function buildPlugin(outfile = defaultOutfile) {
  assertVersionsAligned();
  await build({
    // Pinned so the `// <path>` comments esbuild stamps do not depend on where the build ran.
    absWorkingDir: pkgRoot,
    tsconfig: path.join(pkgRoot, "tsconfig.json"),
    entryPoints: [path.join(pkgRoot, "src/cli.ts")],
    outfile,
    bundle: true,
    platform: "node",
    // `skills *` must run on any supported Node; graph commands still need node:sqlite (>= 22.5).
    target: "node18",
    format: "cjs",
    // Unminified it is ~900 KiB, 550 of them zod's classic API (whose `z` namespace does not
    // tree-shake). Minified it is about half that; nobody reads this file — read src/.
    minify: true,
    plugins: [projectDeps],
    define: { __CODE_GRAPH_VERSION__: JSON.stringify(pkg.version) },
    // version.ts only reads import.meta.url when __CODE_GRAPH_VERSION__ is undefined — never here.
    logOverride: { "empty-import-meta": "silent" },
    banner: { js: BANNER },
    legalComments: "none",
  });
  return outfile;
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const outfile = await buildPlugin();
  const kib = (statSync(outfile).size / 1024).toFixed(0);
  process.stdout.write(`built ${path.relative(process.cwd(), outfile)} (${kib} KiB)\n`);
}
